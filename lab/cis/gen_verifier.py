#!/usr/bin/env python3
"""Generate verify_sca.ps1: a read-only, local re-implementation of the Wazuh SCA
evaluator for one policy, for checking CIS hardening without the manager.

usage: uv run -q --with pyyaml python3 gen_verifier.py cis_win2025.yml ids.txt verify_sca.ps1

Semantics mirror the agent actually deployed (Wazuh 5.0.0-rc1, commit aff7a0b, C++ SCA in
src/wazuh_modules/sca/sca_impl): PCRE2 caseless+multiline regex, line-by-line content
matching, Found/NotFound/Invalid rule results, 32-bit registry view and 32-bit child
processes (the agent is a 32-bit exe).  Rules are parsed here; matching happens in the .ps1.
"""
import json, re, sys
import yaml


def rule(text):
    """Mirror RuleEvaluatorFactory::CreateEvaluator (sca_policy_check.cpp)."""
    s = text.strip(' \t')
    neg = s.startswith('not ')
    if neg:
        s = s[4:].strip(' \t')
    i = s.find(' -> ')                       # sca::GetPattern: everything after the first ' -> '
    pattern = s[i + 4:] if i >= 0 else None
    if pattern is not None:
        s = s[:s.find('->')].strip(' \t')    # target: up to the first '->' (note: no spaces)
    typ, _, target = s.partition(':')
    typ = typ[1:] if typ.startswith('!') else typ
    assert typ in ('r', 'c'), text           # this policy only uses registry and command rules
    return {'src': text, 'neg': neg, 't': typ, 'target': target, 'pattern': pattern}


def selftest():
    r = rule(r'r:HKEY_LOCAL_MACHINE\SOFTWARE\X ->EnableAppInstaller -> 0')   # policy typo
    assert (r['target'], r['pattern']) == (r'HKEY_LOCAL_MACHINE\SOFTWARE\X', '0'), r
    r = rule(r'r:HKEY_LOCAL_MACHINE\SOFTWARE\X -> \\*\NETLOGON -> r:A=1, B=1')
    assert r['pattern'] == r'\\*\NETLOGON -> r:A=1, B=1', r
    r = rule('not c:net user -> r:Administrator|Gast')
    assert r['neg'] and r['t'] == 'c' and r['target'] == 'net user' and r['pattern'] == 'r:Administrator|Gast'
    r = rule(r'r:HKEY_LOCAL_MACHINE\SOFTWARE\X')
    assert r['pattern'] is None and not r['neg']


def main(yml, ids_file, out):
    selftest()
    d = yaml.safe_load(open(yml, encoding='utf-8'))
    ids = [int(x) for x in open(ids_file).read().split()]
    checks = [{'id': c['id'], 'cond': c['condition'], 'rules': [rule(x) for x in c['rules']]}
              for c in d['checks']]
    # Wazuh expands %VAR% in rules before parsing; we parse without expanding, so refuse if any exist.
    assert not any(re.search(r'%\w+%', r['src']) for c in checks for r in c['rules'])
    data = json.dumps(checks, ensure_ascii=True, separators=(',', ':'))
    assert "'@" not in data
    ps = PS.replace('__DEFAULT_IDS__', ','.join(map(str, ids))).replace('__CHECKS_JSON__', data)
    open(out, 'w', encoding='utf-8', newline='\r\n').write(ps)


PS = r'''# verify_sca.ps1 - read-only local evaluator of Wazuh SCA checks (generated by gen_verifier.py; do not edit).
# Output: <id> TAB <PASS|FAIL|NA|NOTRUN> TAB <reason>, then a SUMMARY line.
#   NA = Wazuh "Not applicable" (a key/value it needs is missing and nothing failed outright).
# -Ids '36500,36501' (or 'all') evaluates other check IDs than the built-in in-scope list.
param([string]$Ids = '__DEFAULT_IDS__')
$ErrorActionPreference = 'Stop'

# The Wazuh agent is a 32-bit process: its registry reads land in the 32-bit view (WOW6432Node for
# redirected keys) and its commands resolve to SysWOW64 binaries.  Re-run ourselves the same way.
if ([Environment]::Is64BitProcess) {
    & "$env:SystemRoot\SysWOW64\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -ExecutionPolicy Bypass -File $PSCommandPath -Ids $Ids
    exit $LASTEXITCODE
}
# Wazuh runs as SYSTEM, whose %TEMP% is C:\Windows\Temp; the policy's secedit exports land there.
$env:TEMP = "$env:SystemRoot\Temp"; $env:TMP = $env:TEMP

$checks = ConvertFrom-Json @'
__CHECKS_JSON__
'@
$byId = [ordered]@{}; foreach ($c in $checks) { $byId[[string]$c.id] = $c }
$rxOpt = [Text.RegularExpressions.RegexOptions]'IgnoreCase, Multiline'   # = PCRE2_CASELESS | PCRE2_MULTILINE
$oem = [Text.Encoding]::GetEncoding([Globalization.CultureInfo]::CurrentCulture.TextInfo.OEMCodePage)
$CmdTimeoutSec = 30   # sca.commands_timeout default

function Short([string]$s, [int]$n = 70) { $s = ($s -replace '\s+', ' ').Trim(); if ($s.Length -gt $n) { $s.Substring(0, $n) + '...' } else { $s } }
function Res([string]$r, [string]$why) { [pscustomobject]@{ r = $r; why = $why } }   # r: F=Found N=NotFound I=Invalid S=NotRun
function Neg($res, $neg) { if ($neg -and $res.r -eq 'F') { Res 'N' "NOT: $($res.why)" } elseif ($neg -and $res.r -eq 'N') { Res 'F' "NOT: $($res.why)" } else { $res } }
function StoI([string]$s) { if ($s -match '^\s*([+-]?\d+)') { return [int]$Matches[1] } ; throw "stoi('$s')" }   # [int] overflow throws like std::stoi

# sca_utils.cpp EvaluateMinterm
function Test-Minterm([string]$m, [string]$line) {
    if ($m.StartsWith('r:')) { return [regex]::IsMatch($line, $m.Substring(2), $rxOpt) }
    if ($m.StartsWith('n:')) {
        $e = $m.Substring(2); $p = $e.IndexOf('compare')
        if ($p -lt 0) { throw "'compare' missing" }
        $op, $num = -split $e.Substring($p + 8)
        if (-not $op -or -not $num) { throw 'bad comparison' }
        $want = StoI $num
        $mm = [regex]::Match($line, $e.Substring(0, $p - 1), $rxOpt)
        if (-not $mm.Success) { return $false }
        $v = StoI $(if ($mm.Groups.Count -ge 2 -and $mm.Groups[1].Success) { $mm.Groups[1].Value } else { $mm.Value })
        switch ($op) { '<' { return $v -lt $want } '<=' { return $v -le $want } '==' { return $v -eq $want }
                       '!=' { return $v -ne $want } '>=' { return $v -ge $want } '>' { return $v -gt $want } }
        throw "bad operator $op"
    }
    return $line -ceq $m
}
# sca_utils.cpp PatternMatches: '&&' minterms, each may be '!'-negated, all must hold on one line
# (split on \n only, so lines keep a trailing \r).  A lone negated minterm means "no line matches".
# Throws on a bad regex/number; every caller in the agent turns that into "not found".
function Test-Pattern([string]$content, [string]$pattern) {
    if ($content.Length -eq 0) { return $false }
    $terms = New-Object Collections.ArrayList
    foreach ($t in $pattern.Split([string[]]@(' && '), 'None')) { [void]$terms.Add($(if ($t.StartsWith('!')) { @($true, $t.Substring(1)) } else { @($false, $t) })) }
    $lines = $content.Split([char]"`n"); if ($content.EndsWith("`n")) { $lines = $lines[0..($lines.Count - 2)] }
    if ($terms.Count -eq 1 -and $terms[0][0]) {
        foreach ($l in $lines) { if (Test-Minterm $terms[0][1] $l) { return $false } }
        return $true
    }
    foreach ($l in $lines) {
        $all = $true
        foreach ($t in $terms) { if ((Test-Minterm $t[1] $l) -eq $t[0]) { $all = $false; break } }
        if ($all) { return $true }
    }
    return $false
}
function Try-Pattern([string]$content, [string]$pattern) { try { Test-Pattern $content $pattern } catch { $false } }
function Is-RxOrNum([string]$p) { $p -match '^!?[rn]:' }

# Registry::getValue: SZ/EXPAND_SZ raw, DWORD/QWORD unsigned decimal, MULTI_SZ space-joined; other types -> $null
function Get-WazuhValue($k, [string]$name) {
    if (@($k.GetValueNames()) -notcontains $name) { return $null }
    $raw = $k.GetValue($name, $null, 'DoNotExpandEnvironmentNames')
    switch ($k.GetValueKind($name)) {
        'String'       { return [string]$raw }
        'ExpandString' { return [string]$raw }
        'DWord'        { return [string][BitConverter]::ToUInt32([BitConverter]::GetBytes([int32]$raw), 0) }
        'QWord'        { return [string][BitConverter]::ToUInt64([BitConverter]::GetBytes([int64]$raw), 0) }
        'MultiString'  { return (@($raw) -join ' ') }
    }
    return $null
}

# sca_policy_check_win.cpp RegistryRuleEvaluator
function Test-Reg($r, $view) {
    $hive, $sub = $r.target.Split([char[]]'\', 2)
    try {
        $k = if ($hive -ceq 'HKEY_LOCAL_MACHINE' -or $hive -ceq 'HKLM') { [Microsoft.Win32.RegistryKey]::OpenBaseKey('LocalMachine', $view).OpenSubKey([string]$sub) }
    } catch { return Res 'I' "cannot open key: $($_.Exception.Message)" }
    try {
        if ($null -eq $r.pattern) { return Neg $(if ($k) { Res 'F' 'key exists' } else { Res 'N' 'key missing' }) $r.neg }
        if (-not $k) { return Res 'I' 'key missing' }
        $i = $r.pattern.IndexOf(' -> ')
        if ($i -ge 0) {
            $vn = $r.pattern.Substring(0, $i); $content = $r.pattern.Substring($i + 4)
            $s = Get-WazuhValue $k $vn
            if ($null -eq $s) { return Res 'I' "value $vn missing" }
            $ok = if (Is-RxOrNum $content) { Try-Pattern $s $content } else { [string]::Equals($s, $content, 'OrdinalIgnoreCase') }
            return Neg $(if ($ok) { Res 'F' "$vn='$(Short $s 40)' matches $content" } else { Res 'N' "$vn='$(Short $s 40)' does not match $content" }) $r.neg
        }
        # no ' -> ' in the pattern: is there a subkey or value with that name?
        $rx = $r.pattern -match '^!?r:'
        $hit = @($k.GetSubKeyNames()) + @($k.GetValueNames()) | Where-Object { if ($rx) { Try-Pattern $_ $r.pattern } else { [string]::Equals($_, $r.pattern, 'OrdinalIgnoreCase') } } | Select-Object -First 1
        return Neg $(if ($null -ne $hit) { Res 'F' "$($r.pattern) exists" } else { Res 'N' "no subkey/value named $($r.pattern)" }) $r.neg
    } finally { if ($k) { $k.Close() } }
}

# wm_exec: CreateProcess on the raw command line, stdout+stderr in one pipe.
$cmdCache = @{}
function Get-CmdOutput([string]$cmd) {
    if ($cmdCache.ContainsKey($cmd)) { return $cmdCache[$cmd] }
    $exe, $rest = $cmd.Trim().Split([char[]]" `t", 2)
    $psi = New-Object Diagnostics.ProcessStartInfo $exe, ([string]$rest)
    $psi.UseShellExecute = $false; $psi.CreateNoWindow = $true
    $psi.RedirectStandardOutput = $true; $psi.RedirectStandardError = $true
    $psi.StandardOutputEncoding = $oem; $psi.StandardErrorEncoding = $oem
    try {
        $p = [Diagnostics.Process]::Start($psi)
        $o = $p.StandardOutput.ReadToEndAsync(); $e = $p.StandardError.ReadToEndAsync()
        if ($p.WaitForExit($CmdTimeoutSec * 1000)) { $res = @{ out = $o.Result + $e.Result } }
        else { try { $p.Kill() } catch {} ; $res = @{ timeout = $true } }
    } catch { $res = @{ failed = $_.Exception.Message } }
    $cmdCache[$cmd] = $res
    return $res
}
# sca_policy_check.cpp CommandRuleEvaluator
function Test-Cmd($r) {
    $x = Get-CmdOutput $r.target
    if ($x.failed) { return Res 'I' "command execution failed: $($x.failed)" }
    if ($x.timeout) { return Res 'S' "command timed out after $CmdTimeoutSec s" }
    if ($null -eq $r.pattern) { return Neg (Res 'F' 'command ran') $r.neg }
    $out = $x.out.Trim([char]"`n")
    $ok = if (Is-RxOrNum $r.pattern) { Try-Pattern $out $r.pattern } else { $out -ceq $r.pattern }
    if ($ok) { return Neg (Res 'F' 'output matches') $r.neg }
    $last = @($out.Split([char]"`n") | Where-Object { $_.Trim() }) | Select-Object -Last 1
    return Neg (Res 'N' "no output line matches (last line: '$(Short $last 50)')") $r.neg
}

# check_condition_evaluator.cpp
function Test-Check($c, $view) {
    $rs = @($c.rules); $res = @(foreach ($r in $rs) { if ($r.t -eq 'c') { Test-Cmd $r } else { Test-Reg $r $view } })
    $why = { param($i) "$(Short $rs[$i].src): $($res[$i].why)" }
    $idx = 0..($rs.Count - 1)
    $nf = @($idx | Where-Object { $res[$_].r -eq 'N' }); $fd = @($idx | Where-Object { $res[$_].r -eq 'F' })
    $bad = @($idx | Where-Object { $res[$_].r -in 'I', 'S' })
    if ($c.cond -eq 'all' -and $nf.Count) { return @('FAIL', (& $why $nf[0])) }
    if ($c.cond -eq 'any' -and $fd.Count) { return @('PASS', '') }
    if ($c.cond -eq 'none' -and $fd.Count) { return @('FAIL', "rule matched: $(& $why $fd[0])") }
    if (@($idx | Where-Object { $res[$_].r -eq 'S' }).Count) { return @('NOTRUN', (& $why $bad[0])) }
    if ($bad.Count) { return @('NA', (($bad | ForEach-Object { & $why $_ }) -join ' | ')) }
    if ($c.cond -eq 'any') { return @('FAIL', "no rule matched; first: $(& $why 0)") }
    return @('PASS', '')
}

$n = [ordered]@{ PASS = 0; FAIL = 0; NA = 0; NOTRUN = 0; ERROR = 0 }
$list = if ($Ids -eq 'all') { $byId.Keys } else { $Ids -split '[,\s]+' | Where-Object { $_ } }
foreach ($id in $list) {
    $c = $byId[$id]
    if (-not $c) { "$id`tERROR`tno such check in policy"; $n.ERROR++; continue }
    try {
        $v = Test-Check $c 'Registry32'
        # Would it come out differently if the agent read the native 64-bit registry view?
        if (@($c.rules | Where-Object { $_.t -eq 'r' }).Count) {
            $v64 = Test-Check $c 'Registry64'
            if ($v64[0] -ne $v[0]) { $v[1] += " [64-bit registry view would give $($v64[0]); Wazuh's 32-bit agent reads WOW6432Node]" }
        }
    } catch { $v = @('ERROR', "evaluator error: $($_.Exception.Message) @ line $($_.InvocationInfo.ScriptLineNumber)") }
    "$id`t$($v[0])`t$($v[1])"
    $n[$v[0]]++
}
"SUMMARY`t" + (($n.Keys | ForEach-Object { "$_=$($n[$_])" }) -join "`t") + "`tTOTAL=$(@($list).Count)"
'''

if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:4])
